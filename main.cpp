#include <string>
#include <vector>

void vector_max() {
    std::vector<int> values;
    values.push_back(11);
    values.push_back(29);
    values.push_back(7);
    int best = values[0];
    for (std::size_t i = 1; i < values.size(); ++i) {
        if (values[i] > best) best = values[i];
    }
    (void)best;
}

void absolute_diff() {
    int a = 41, b = 90;
    int diff = (a > b) ? (a - b) : (b - a);
    (void)diff;
}

void sum_evens() {
    int values[5] = {2, 4, 6, 8, 10};
    int acc = 0;
    for (int i = 0; i < 5; ++i) acc += values[i];
    (void)acc;
}

void is_prime() {
    int n = 97;
    bool prime = (n > 1);
    for (int d = 2; d * d <= n; ++d) {
        if (n % d == 0) { prime = false; break; }
    }
    (void)prime;
}

extern "C" int frost_crescent();
extern "C" void cobalt_quartz();
extern "C" void sable_haven();

int main() {
    vector_max();
    absolute_diff();
    sum_evens();
    is_prime();
    cobalt_quartz();
    sable_haven();
    return frost_crescent();
}
